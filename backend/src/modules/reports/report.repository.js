const crypto = require('crypto');
const db = require('../../models');

class ReportRepository {
  buildSafePayload(Model, overrides = {}) {
    const attrs = Model.rawAttributes || {};
    const payload = { ...overrides };

    for (const [key, attr] of Object.entries(attrs)) {
      if (payload[key] !== undefined) continue;
      if (attr.autoIncrement || attr._autoGenerated) continue;
      if (['createdAt', 'updatedAt', 'deletedAt'].includes(key)) continue;
      if (attr.allowNull !== false) continue;
      if (attr.defaultValue !== undefined) continue;

      const typeKey = attr.type?.key || '';
      const suffix = Date.now().toString().slice(-5);

      if (typeKey === 'UUID' || typeKey === 'UUIDV4') {
        payload[key] = crypto.randomUUID();
      } else if (typeKey === 'ENUM' && Array.isArray(attr.values) && attr.values.length > 0) {
        payload[key] = attr.values[0];
      } else if (key.toLowerCase().includes('email')) {
        payload[key] = `reporter-${suffix}@taskmanager.local`;
      } else if (['INTEGER', 'BIGINT', 'SMALLINT', 'FLOAT', 'DOUBLE', 'DECIMAL'].includes(typeKey)) {
        payload[key] = 1;
      } else if (typeKey === 'BOOLEAN') {
        payload[key] = true;
      } else if (['DATE', 'DATEONLY'].includes(typeKey)) {
        payload[key] = new Date();
      } else {
        payload[key] = attr.unique ? `SYSTEM_${suffix}` : 'SYSTEM';
      }
    }

    return payload;
  }

  async findAllTasks(filters = {}) {
    if (!db.Task) return [];

    const where = {};
    if (filters.columnId) where.columnId = filters.columnId;
    if (filters.priority) where.priority = filters.priority;

    const include = [];
    if (db.Task.associations) {
      if (db.Task.associations.column) include.push({ association: 'column' });
      if (db.Task.associations.assignee) include.push({ association: 'assignee' });
      if (db.Task.associations.user) include.push({ association: 'user' });
    }

    const tasks = await db.Task.findAll({
      where,
      include,
      order: [['createdAt', 'DESC']],
    });

    return tasks.map((task) => (typeof task.toJSON === 'function' ? task.toJSON() : task));
  }

  async resolveLookupValue(Model, targetCode, returnField = 'code') {
    if (!Model || !targetCode) return String(targetCode).toUpperCase();

    const upper = String(targetCode).toUpperCase();
    const lower = String(targetCode).toLowerCase();
    const attrs = Model.rawAttributes || {};
    const keyField = attrs[returnField] ? returnField : attrs.code ? 'code' : attrs.id ? 'id' : null;

    if (!keyField) return upper;

    const existingRecords = await Model.findAll();

    if (existingRecords.length > 0) {
      const aliases =
        upper === 'SUCCESS'
          ? ['success', 'completed', 'done', 'ok']
          : upper === 'FAILED'
            ? ['failed', 'error', 'fail']
            : [lower];

      const matched = existingRecords.find((item) =>
        aliases.includes(String(item[keyField]).toLowerCase())
      );

      if (matched) return matched[keyField];
      return existingRecords[0][keyField];
    }

    const overrides = { [keyField]: upper };
    if (attrs.name && keyField !== 'name') overrides.name = upper;
    if (attrs.label && keyField !== 'label') overrides.label = upper;
    if (attrs.description && keyField !== 'description') overrides.description = upper;

    const payload = this.buildSafePayload(Model, overrides);
    const created = await Model.create(payload);
    return created[keyField];
  }

  async resolveRequestedBy(requestedBy, attrDefinition) {
    const typeKey = attrDefinition?.type?.key || '';
    const isNumeric = ['INTEGER', 'BIGINT', 'SMALLINT'].includes(typeKey);
    const isUuid = ['UUID', 'UUIDV4'].includes(typeKey);

    if (requestedBy !== null && requestedBy !== undefined && requestedBy !== '') {
      return isNumeric ? Number(requestedBy) : String(requestedBy);
    }

    if ((isNumeric || isUuid) && db.User) {
      let user = await db.User.findOne({ order: [['id', 'ASC']] });
      if (!user) {
        const userPayload = this.buildSafePayload(db.User, {
          name: 'System Reporter',
          username: 'system',
          email: 'reporter@taskmanager.local',
        });
        user = await db.User.create(userPayload);
      }
      if (user) return user.id;
    }

    return isNumeric ? 1 : 'System';
  }

  async createExportHistory({ format, status, fileName, totalRecords, requestedBy = null, errorMessage = null }) {
    if (!db.ExportHistory) return null;

    const attrs = db.ExportHistory.rawAttributes || {};
    const overrides = {};

    if (attrs.formatId) {
      overrides.formatId = await this.resolveLookupValue(db.ExportFormat, format, 'id');
    } else if (attrs.format) {
      overrides.format = await this.resolveLookupValue(db.ExportFormat, format, 'code');
    }

    if (attrs.statusId) {
      overrides.statusId = await this.resolveLookupValue(db.ExportStatus, status, 'id');
    } else if (attrs.status) {
      overrides.status = await this.resolveLookupValue(db.ExportStatus, status, 'code');
    }

    const requesterAttr = attrs.requestedBy || attrs.exportedBy || attrs.userId;
    const requesterValue = await this.resolveRequestedBy(requestedBy, requesterAttr);
    if (attrs.requestedBy) overrides.requestedBy = requesterValue;
    if (attrs.exportedBy) overrides.exportedBy = requesterValue;
    if (attrs.userId) overrides.userId = requesterValue;

    if (attrs.fileName) overrides.fileName = fileName;
    if (attrs.filename) overrides.filename = fileName;
    if (attrs.filePath) overrides.filePath = `/exports/${fileName}`;
    if (attrs.totalRecords !== undefined) overrides.totalRecords = totalRecords;
    if (attrs.totalTasks !== undefined) overrides.totalTasks = totalRecords;
    if (attrs.rowCount !== undefined) overrides.rowCount = totalRecords;
    if (attrs.errorMessage !== undefined && errorMessage) overrides.errorMessage = errorMessage;

    const payload = this.buildSafePayload(db.ExportHistory, overrides);
    return db.ExportHistory.create(payload);
  }

  async findAllHistory(limit = 20) {
    if (!db.ExportHistory) return [];

    return db.ExportHistory.findAll({
      order: [['createdAt', 'DESC']],
      limit,
    });
  }
}

module.exports = ReportRepository;